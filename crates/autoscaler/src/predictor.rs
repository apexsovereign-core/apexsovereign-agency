use std::collections::VecDeque;
use std::sync::Arc;
use std::time::{Duration, Instant};
use chrono::{DateTime, Utc};
use parking_lot::RwLock;
use serde::{Deserialize, Serialize};
use tokio::sync::mpsc;
use tracing::{debug, error, info, warn};

/// Metric sample recorded per second from streaming ingress gateways.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MetricSample {
    pub timestamp: DateTime<Utc>,
    pub request_rate: f64,          // requests per second
    pub token_generation_rate: f64, // tokens per second
    pub active_vcu_allocated: u32,  // currently allocated Virtual Compute Units
    pub cluster_capacity_vcu: u32,  // total cluster VCU capacity
    pub vram_usage_gb: f64,
    pub nvlink_bandwidth_util: f64, // 0.0 - 1.0
}

/// Holt-Winters smoothing hyperparameters.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HoltWintersConfig {
    pub alpha: f64,             // Level smoothing factor [0, 1]
    pub beta: f64,              // Trend smoothing factor [0, 1]
    pub gamma: f64,             // Seasonal smoothing factor [0, 1]
    pub season_length: usize,   // Seasonal cycle in sample steps (e.g. 60 seconds)
    pub forecast_horizon_sec: usize, // Lookahead window (default: 60s)
    pub saturation_threshold: f64,   // Trigger scale-up threshold (default: 0.80 = 80%)
    pub emergency_shed_threshold: f64, // Shed standard/spot threshold (default: 0.92 = 92%)
    pub tokens_per_vcu_sec: f64,     // Throughput capacity per B200 VCU (default: 450.0 tokens/sec)
}

impl Default for HoltWintersConfig {
    fn default() -> Self {
        Self {
            alpha: 0.35,
            beta: 0.15,
            gamma: 0.25,
            season_length: 60,
            forecast_horizon_sec: 60,
            saturation_threshold: 0.80,
            emergency_shed_threshold: 0.92,
            tokens_per_vcu_sec: 450.0,
        }
    }
}

/// Holt-Winters internal state tracker.
#[derive(Debug, Clone)]
pub struct HoltWintersState {
    pub level: f64,
    pub trend: f64,
    pub seasonal: Vec<f64>,
    pub step_count: usize,
    pub initialized: bool,
}

impl HoltWintersState {
    pub fn new(season_length: usize) -> Self {
        Self {
            level: 0.0,
            trend: 0.0,
            seasonal: vec![1.0; season_length], // Multiplicative seasonal baseline
            step_count: 0,
            initialized: false,
        }
    }
}

/// Fixed-duration sliding window ring buffer (900 seconds = 15 minutes).
pub struct MetricRingBuffer {
    max_capacity: usize,
    samples: VecDeque<MetricSample>,
}

impl MetricRingBuffer {
    pub fn new(max_capacity: usize) -> Self {
        Self {
            max_capacity,
            samples: VecDeque::with_capacity(max_capacity),
        }
    }

    pub fn push(&mut self, sample: MetricSample) {
        if self.samples.len() >= self.max_capacity {
            self.samples.pop_front();
        }
        self.samples.push_back(sample);
    }

    pub fn latest(&self) -> Option<&MetricSample> {
        self.samples.back()
    }

    pub fn len(&self) -> usize {
        self.samples.len()
    }

    pub fn is_empty(&self) -> bool {
        self.samples.is_empty()
    }

    pub fn as_slice(&self) -> Vec<MetricSample> {
        self.samples.iter().cloned().collect()
    }
}

/// Forecast output generated by the predictive engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CapacityForecast {
    pub generated_at: DateTime<Utc>,
    pub horizon_seconds: usize,
    pub current_token_rate: f64,
    pub forecasted_token_rate: f64,
    pub current_vcu_demand: u32,
    pub forecasted_vcu_demand: u32,
    pub active_capacity_vcu: u32,
    pub predicted_saturation: f64,
    pub scaling_action_required: bool,
    pub target_vcu_provision: u32,
    pub emergency_shed_active: bool,
}

/// Dispatched preemptive cluster scaling instruction.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PreemptiveScaleEvent {
    pub event_id: String,
    pub timestamp: DateTime<Utc>,
    pub current_capacity_vcu: u32,
    pub target_capacity_vcu: u32,
    pub delta_vcu: i32,
    pub trigger_reason: String,
    pub forecasted_saturation: f64,
    pub execution_deadline: DateTime<Utc>,
}

/// Core Predictive Workload Auto-Scaler.
pub struct PredictiveEngine {
    config: HoltWintersConfig,
    ring_buffer: Arc<RwLock<MetricRingBuffer>>,
    hw_state: Arc<RwLock<HoltWintersState>>,
    scale_event_sender: mpsc::Sender<PreemptiveScaleEvent>,
}

impl PredictiveEngine {
    pub fn new(
        config: HoltWintersConfig,
        scale_event_sender: mpsc::Sender<PreemptiveScaleEvent>,
    ) -> Self {
        let season_len = config.season_length;
        Self {
            config,
            ring_buffer: Arc::new(RwLock::new(MetricRingBuffer::new(900))), // 15-min history at 1s
            hw_state: Arc::new(RwLock::new(HoltWintersState::new(season_len))),
            scale_event_sender,
        }
    }

    /// Ingests a new metric sample from the streaming ingress gateway.
    pub async fn ingest_metric(&self, sample: MetricSample) -> CapacityForecast {
        {
            let mut buf = self.ring_buffer.write();
            buf.push(sample.clone());
        }

        let forecast = self.update_and_forecast(sample.token_generation_rate, sample.cluster_capacity_vcu);

        if forecast.scaling_action_required {
            let event = PreemptiveScaleEvent {
                event_id: format!("scale-preempt-{}", Utc::now().timestamp_nanos_opt().unwrap_or(0)),
                timestamp: Utc::now(),
                current_capacity_vcu: forecast.active_capacity_vcu,
                target_capacity_vcu: forecast.target_vcu_provision,
                delta_vcu: forecast.target_vcu_provision as i32 - forecast.active_capacity_vcu as i32,
                trigger_reason: format!(
                    "Forecasted saturation {:.2}% exceeds threshold {:.2}% in {}s lookahead",
                    forecast.predicted_saturation * 100.0,
                    self.config.saturation_threshold * 100.0,
                    self.config.forecast_horizon_sec
                ),
                forecasted_saturation: forecast.predicted_saturation,
                execution_deadline: Utc::now() + chrono::Duration::seconds(self.config.forecast_horizon_sec as i64),
            };

            info!(
                event_id = %event.event_id,
                current_vcu = event.current_capacity_vcu,
                target_vcu = event.target_capacity_vcu,
                forecasted_saturation = %format!("{:.2}%", event.forecasted_saturation * 100.0),
                "Dispatching preemptive B200 cluster scaling command"
            );

            if let Err(e) = self.scale_event_sender.send(event).await {
                error!(error = %e, "Failed to send preemptive scale event through IPC channel");
            }
        }

        forecast
    }

    /// Evaluates additive/multiplicative Holt-Winters update equations.
    pub fn update_and_forecast(&self, observed_token_rate: f64, total_capacity_vcu: u32) -> CapacityForecast {
        let mut state = self.hw_state.write();
        let season_len = self.config.season_length;
        let season_idx = state.step_count % season_len;

        if !state.initialized {
            state.level = observed_token_rate;
            state.trend = 0.0;
            state.seasonal[season_idx] = 1.0;
            state.initialized = true;
            state.step_count += 1;

            let required_vcu = (observed_token_rate / self.config.tokens_per_vcu_sec).ceil() as u32;
            let current_saturation = if total_capacity_vcu > 0 {
                required_vcu as f64 / total_capacity_vcu as f64
            } else {
                1.0
            };

            return CapacityForecast {
                generated_at: Utc::now(),
                horizon_seconds: self.config.forecast_horizon_sec,
                current_token_rate: observed_token_rate,
                forecasted_token_rate: observed_token_rate,
                current_vcu_demand: required_vcu,
                forecasted_vcu_demand: required_vcu,
                active_capacity_vcu: total_capacity_vcu,
                predicted_saturation: current_saturation,
                scaling_action_required: current_saturation >= self.config.saturation_threshold,
                target_vcu_provision: required_vcu.max(total_capacity_vcu),
                emergency_shed_active: current_saturation >= self.config.emergency_shed_threshold,
            };
        }

        let prev_level = state.level;
        let prev_trend = state.trend;
        let seasonal_factor = if state.seasonal[season_idx] > 0.001 {
            state.seasonal[season_idx]
        } else {
            1.0
        };

        // Multiplicative Holt-Winters updating:
        // 1. Level update: L_t = alpha * (Y_t / S_{t-m}) + (1 - alpha) * (L_{t-1} + b_{t-1})
        let des_val = observed_token_rate / seasonal_factor;
        let new_level = self.config.alpha * des_val + (1.0 - self.config.alpha) * (prev_level + prev_trend);

        // 2. Trend update: b_t = beta * (L_t - L_{t-1}) + (1 - beta) * b_{t-1}
        let new_trend = self.config.beta * (new_level - prev_level) + (1.0 - self.config.beta) * prev_trend;

        // 3. Seasonal update: S_t = gamma * (Y_t / L_t) + (1 - gamma) * S_{t-m}
        let new_seasonal = if new_level > 0.001 {
            self.config.gamma * (observed_token_rate / new_level) + (1.0 - self.config.gamma) * seasonal_factor
        } else {
            1.0
        };

        state.level = new_level;
        state.trend = new_trend;
        state.seasonal[season_idx] = new_seasonal;
        state.step_count += 1;

        // 4. Point forecast for h = forecast_horizon_sec steps ahead:
        //    Y_{t+h} = (L_t + h * b_t) * S_{t - m + ((h - 1) % m) + 1}
        let h = self.config.forecast_horizon_sec as f64;
        let future_season_idx = (state.step_count + self.config.forecast_horizon_sec) % season_len;
        let future_seasonal = state.seasonal[future_season_idx].max(0.5).min(2.5);

        let forecasted_token_rate = ((new_level + h * new_trend) * future_seasonal).max(0.0);

        let current_vcu_demand = (observed_token_rate / self.config.tokens_per_vcu_sec).ceil() as u32;
        let forecasted_vcu_demand = (forecasted_token_rate / self.config.tokens_per_vcu_sec).ceil() as u32;

        let predicted_saturation = if total_capacity_vcu > 0 {
            forecasted_vcu_demand as f64 / total_capacity_vcu as f64
        } else {
            1.0
        };

        let scaling_action_required = predicted_saturation >= self.config.saturation_threshold;
        let emergency_shed_active = predicted_saturation >= self.config.emergency_shed_threshold;

        // Add 25% safety headroom above forecasted demand when scaling
        let target_vcu_provision = if scaling_action_required {
            ((forecasted_vcu_demand as f64 * 1.25).ceil() as u32).max(total_capacity_vcu + 2)
        } else {
            total_capacity_vcu
        };

        CapacityForecast {
            generated_at: Utc::now(),
            horizon_seconds: self.config.forecast_horizon_sec,
            current_token_rate: observed_token_rate,
            forecasted_token_rate,
            current_vcu_demand,
            forecasted_vcu_demand,
            active_capacity_vcu: total_capacity_vcu,
            predicted_saturation,
            scaling_action_required,
            target_vcu_provision,
            emergency_shed_active,
        }
    }

    /// Read historical metrics buffer for diagnostics and visual telemetry.
    pub fn get_history(&self) -> Vec<MetricSample> {
        self.ring_buffer.read().as_slice()
    }
}
